import { expect,it } from "vitest";
import { apiKeySecretHint,generateApiKeySecret,hashApiKeySecret } from "@agent-hub/core";
import { DEMO_MEMBER,DEMO_ORG,getMockDb } from "@agent-hub/db";
import { GET as documents } from "@/app/api/v1/sources/[id]/documents/route";
import { POST as review,DELETE as removeReview } from "@/app/api/v1/sources/[id]/documents/[documentId]/review/route";
import { PATCH as updateFaq } from "@/app/api/v1/sources/[id]/faq/route";
import { GET as history } from "@/app/api/v1/sources/[id]/faq/history/route";
import { POST as restore } from "@/app/api/v1/sources/[id]/faq/restore/route";
it("runs Document review and the FAQ edit/restore lifecycle through an actual API key and pinned Db", async () => {
  const db=getMockDb();
  const secret=generateApiKeySecret();
  await db.createApiKey(DEMO_ORG.id,{ name:"Quality API fixture",role:"editor", roleId: "builtin:editor",secretHash:hashApiKeySecret(secret),secretHint:apiKeySecretHint(secret),createdBy:DEMO_MEMBER.userId });
  const collection=await db.getOrCreateOrgLibraryCollection(DEMO_ORG.id);
  const source=await db.createSource({ collectionId:collection.id,name:"Original question",kind:"faq" });
  const concept=await db.createConcept({ collectionId:collection.id,sourceId:source.id,path:"faq/api-quality.md",frontmatter:{ type:"FAQ",title:"Original question" },body:"Original answer" });
  const request=(method="GET",body?:unknown) => new Request(`http://test.local/api/v1/sources/${source.id}`,{ method,headers:{ authorization:`Bearer ${secret}`,"content-type":"application/json" },...(body ? { body:JSON.stringify(body) } : {}) });
  const params={ params:Promise.resolve({ id:source.id }) };
  const documentParams={ params:Promise.resolve({ id:source.id,documentId:concept.id }) };
  expect((await documents(request(),params)).status).toBe(200);
  const marked=await review(request("POST"),documentParams);
  expect(marked.status).toBe(200);
  expect((await marked.json()).frontmatter.verified).toEqual([expect.objectContaining({ by:`human:${DEMO_MEMBER.userId}` })]);
  expect((await removeReview(request("DELETE"),documentParams)).status).toBe(204);
  const edited=await updateFaq(request("PATCH",{ question:"Changed question",answer:"Changed answer" }),params);
  expect(edited.status).toBe(200);
  const versions=await history(request(),params);
  expect(versions.status).toBe(200);
  const [version]=(await versions.json()).data;
  expect(version).toMatchObject({ question:"Original question",answer:"Original answer" });
  const restored=await restore(request("POST",{ versionId:version.id }),params);
  expect(restored.status).toBe(200);
  expect((await restored.json()).answer).toBe("Original answer");
});
