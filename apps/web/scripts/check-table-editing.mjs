import assert from "node:assert/strict";
import { chromium } from "playwright-core";
const base = process.env.TABLE_LAYOUT_BASE_URL ?? "http://localhost:3145";
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1500, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on("pageerror", error => errors.push(error.message));
async function ready(route) {
  if (route) await page.goto(new URL(route, base).href);
  await page.locator("tbody tr").first().waitFor();
  await page.waitForFunction(() => document.querySelector("table")?.style.getPropertyValue("--table-width"));
  await page.evaluate(() => document.fonts.ready);
}
const rowIds = () => page.locator("tbody tr").evaluateAll(rows => rows.map(row => row.dataset.tableRowId));
const columnIds = () => page.locator("table col").evaluateAll(cols => cols.map(col => col.dataset.column));
const websiteRow = () => page.locator("tbody tr").first();
const nameField = () => page.getByRole("textbox", { name: "Source name", exact: true });
try {
  await ready("/alerts");
  assert.equal(await page.getByText("Drag handles to move rows or columns", { exact: true }).count(), 0);
  assert.equal(await page.getByText("Shift-click to select cells", { exact: true }).count(), 0);
  const initialRows = await rowIds(), initialColumns = await columnIds();
  assert.equal(await page.locator('[data-slot="row-drag-handle"]').count(), 0);
  await page.getByRole("button", { name: "Move category column", exact: true }).press("Alt+ArrowRight");
  const movedColumns = await columnIds();
  assert.deepEqual(await rowIds(), initialRows); assert.notDeepEqual(movedColumns, initialColumns);
  const keys = await page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith("ciele.table-order.")));
  assert.equal(keys.length, 1); assert.ok(keys[0].includes("demo-user") && keys[0].endsWith(".columns"), "only column order is stored, scoped to the member");
  await page.evaluate(({ key, rows }) => localStorage.setItem(key.replace(/\.columns$/, ".rows"), JSON.stringify(rows.toReversed())), { key: keys[0], rows: initialRows });
  await page.reload(); await ready();
  assert.deepEqual(await rowIds(), initialRows, "legacy cached row order is ignored"); assert.deepEqual(await columnIds(), movedColumns);
  const other = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
  await other.goto(new URL("/alerts", base).href); await other.locator("tbody tr").first().waitFor();
  assert.deepEqual(await other.locator("tbody tr").evaluateAll(rows => rows.map(row => row.dataset.tableRowId)), initialRows);
  await other.close();
  await page.evaluate(() => localStorage.clear()); await page.reload(); await ready();
  assert.deepEqual(await rowIds(), initialRows); assert.deepEqual(await columnIds(), initialColumns);
  console.log("PASS local preferences: refresh restores columns and ignores legacy row order; another browser sees the server order; clearing site storage resets columns");

  await ready("/library/websites");
  const url = await websiteRow().locator("td").nth(2).innerText();
  const originalName = await websiteRow().locator("td").nth(1).locator("scritto-text").first().getAttribute("aria-label");
  const rowHeight = await websiteRow().evaluate(row => row.getBoundingClientRect().height);
  await websiteRow().locator("td").nth(1).dblclick();
  assert.equal(await nameField().inputValue(), originalName);
  assert.ok(Math.abs(await websiteRow().evaluate(row => row.getBoundingClientRect().height) - rowHeight) < 1, "single-line editing keeps row height stable");
  await nameField().fill("Cancelled edit"); await nameField().press("Escape");
  assert.equal(await nameField().count(), 0);
  assert.ok(await websiteRow().locator("td").nth(1).evaluate(cell => cell === document.activeElement), "Escape returns focus to the cell");
  await websiteRow().locator("td").nth(1).press("F2");
  await nameField().fill("Browser editing check"); await nameField().press("Enter");
  await nameField().waitFor({ state: "detached" });
  await page.reload(); await ready();
  await websiteRow().locator("td").nth(1).dblclick();
  assert.equal(await nameField().inputValue(), "Browser editing check");
  await nameField().fill(originalName); await nameField().press("Enter"); await nameField().waitFor({ state: "detached" });
  for (const index of [2, 5, 6, 7]) {
    const cell = websiteRow().locator("td").nth(index);
    assert.equal(await cell.getAttribute("data-cell-editable"), null);
    await cell.dblclick({ position: { x: 8, y: 8 } });
    assert.equal(await page.locator('[data-cell-editing="true"]').count(), 0);
  }
  assert.equal(await websiteRow().locator("td").nth(2).innerText(), url);
  await websiteRow().locator("td").nth(4).dblclick({ position: { x: 8, y: 8 } });
  await page.getByRole("dialog").waitFor();
  assert.ok((await page.getByRole("dialog").innerText()).includes("assistant"));
  await page.keyboard.press("Escape");
  console.log("PASS knowledge: name saves and Escape cancels; URL/status/dates remain read-only; linked assistants open their editor");

  await ready("/alerts");
  const alertRow = page.locator('tbody tr[data-table-row-id*="alert-demo-crm"]');
  await alertRow.locator("td").nth(0).dblclick();
  await page.getByRole("menuitem", { name: "Knowledge", exact: true }).click();
  await page.getByRole("menu").waitFor({ state: "detached" });
  await page.reload(); await ready();
  assert.equal(await alertRow.locator("td").nth(0).innerText(), "Knowledge");
  await alertRow.locator("td").nth(0).dblclick();
  await page.getByRole("menuitem", { name: "Integration", exact: true }).click();
  await page.getByRole("menu").waitFor({ state: "detached" });
  await alertRow.locator("td").nth(1).dblclick();
  const issue = page.getByRole("textbox", { name: "Issue", exact: true });
  const originalIssue = await issue.inputValue();
  await issue.fill("Edited issue\nEdited description"); await issue.press("Control+Enter"); await issue.waitFor({ state: "detached" });
  await page.reload(); await ready(); await alertRow.locator("td").nth(1).dblclick();
  assert.equal(await issue.inputValue(), "Edited issue\nEdited description");
  await issue.fill(originalIssue); await issue.press("Control+Enter"); await issue.waitFor({ state: "detached" });
  await alertRow.locator("td").nth(4).dblclick(); await page.getByRole("menuitem", { name: "Resolved", exact: true }).click();
  await page.getByRole("menu").waitFor({ state: "detached" });
  await page.reload(); await ready();
  assert.ok(await alertRow.locator("td").nth(3).locator("scritto-text").first().getAttribute("aria-label") !== "N/A");
  await alertRow.locator("td").nth(4).dblclick(); await page.getByRole("menuitem", { name: "Active", exact: true }).click();
  await page.getByRole("menu").waitFor({ state: "detached" });
  await page.reload(); await ready();
  assert.equal(await alertRow.locator("td").nth(3).locator("scritto-text").first().getAttribute("aria-label"), "N/A");
  console.log("PASS Alerts: category, issue and description persist; resolving/reopening controls the system resolution date");

  await ready("/settings/members");
  const member = page.locator('tbody tr[data-table-row-id*="u-marco"]');
  const role = member.locator("td").nth(3);
  assert.equal(await page.locator('[data-slot="table-category"][data-tone="purple"]').count(), 1);
  assert.equal(await role.locator('[data-slot="table-category"]').getAttribute("data-tone"), "blue");
  await role.click(); assert.equal(await page.getByRole("menu").count(), 0);
  await role.dblclick(); await page.getByRole("menu").waitFor();
  assert.deepEqual(await page.getByRole("menuitem").allTextContents(), ["Owner", "Admin", "Editor", "Viewer"]);
  await page.getByRole("menuitem", { name: "Viewer", exact: true }).click();
  await page.getByRole("menu").waitFor({ state: "detached" }); await page.reload(); await ready();
  assert.equal(await role.locator('[data-slot="table-category"]').getAttribute("data-tone"), "gray");
  await role.dblclick(); await page.getByRole("menuitem", { name: "Admin", exact: true }).click();
  await page.getByRole("menu").waitFor({ state: "detached" }); await page.reload(); await ready();
  assert.equal(await page.locator('tbody tr[data-table-row-id*="demo-user"] td').nth(3).getAttribute("data-cell-editable"), null);
  await role.dblclick(); await page.getByRole("menuitem", { name: "Owner", exact: true }).click();
  assert.ok((await page.getByRole("dialog").last().innerText()).includes("Make"));
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  assert.equal(await role.locator('[data-slot="table-category"]').getAttribute("data-tone"), "blue");
  console.log("PASS members: colored roles; single-click stays in display mode; double-click edits; self-role stays locked; ownership retains confirmation");
  assert.deepEqual(errors, []);
} finally { await browser.close(); }
