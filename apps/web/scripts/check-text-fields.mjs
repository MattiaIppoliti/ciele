import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';

// Exercises the real app's delegated behavior, including fields mounted later
// in dialogs. The only app edit is an unsaved new Flow name; no form is saved.
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1400, height: 1000 }, colorScheme: 'dark' });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const caret = page.locator('[data-slot="smooth-field-caret"]');
const visibleCaret = () => page.waitForFunction(() => document.querySelector('[data-slot="smooth-field-caret"]')?.style.opacity === '1');
try {
  await page.goto(new URL('/assistants/Vrp47KxooVPk/flows/new', process.env.TEXT_FIELDS_BASE_URL ?? 'http://localhost:3000').href, { timeout: 120000 });
  const name = page.getByRole('textbox', { name: 'Flow name', exact: true });
  await name.waitFor();
  await name.focus();
  await visibleCaret();
  await name.press('Tab');
  assert.equal(await name.inputValue(), 'Name this flow…', 'Tab updates the real controlled Base UI field');
  assert.equal(await name.evaluate(e => e === document.activeElement), true);
  await name.press('ControlOrMeta+z');
  assert.equal(await name.inputValue(), '', 'completion preserves native undo and React state');
  await name.fill('Nam');
  await page.waitForTimeout(200);
  await name.screenshot({ path: '/tmp/pr1021-smooth-name.png' });
  await name.press('Tab');
  assert.equal(await name.inputValue(), 'Name this flow…');
  await name.fill('');
  const composer = page.getByRole('textbox', { name: 'Ask Ciele AI', exact: true });
  await composer.fill('Ask');
  await composer.press('Tab');
  assert.equal(await composer.inputValue(), 'Ask Ciele AI…', 'composer receives the same completion');
  assert.equal(await caret.count(), 1, 'there is one painter, including the composer');
  await composer.fill('');

  await page.evaluate(() => {
    const fixture = document.createElement('div');
    fixture.id = 'text-field-check';
    fixture.style.cssText = 'position:fixed;left:20px;top:100px;width:280px;padding:12px;z-index:99999;background:var(--background);color:var(--foreground)';
    fixture.innerHTML = `<input id="check-first" placeholder="Alpha beta"><input id="check-plain" placeholder="Alpha beta"><input id="check-last"><textarea id="check-lines" placeholder="Hello there"></textarea><input id="check-secret" type="password" placeholder="secret"><input id="check-revealed" data-text-completion="off" placeholder="secret"><input id="check-number" type="number"><input id="check-email" type="email" placeholder="me@example.com"><input id="check-list" list="check-options"><datalist id="check-options"><option value="Hello world"></datalist><input id="check-readonly" readonly placeholder="Alpha"><input id="check-max" maxlength="4" placeholder="Alpha beta">`;
    for (const e of fixture.querySelectorAll('input,textarea')) e.style.cssText = 'display:block;width:240px;height:32px;border:1px solid;padding:4px 8px;font:16px/22px monospace;background:transparent;color:inherit;margin:4px 0';
    fixture.querySelector('textarea').style.height = '80px';
    document.body.append(fixture);
  });
  const plain = page.locator('#check-plain');
  await plain.fill('Al');
  await visibleCaret();
  await page.waitForTimeout(200);
  const start = await caret.boundingBox();
  await plain.press('p');
  const intermediate = await caret.boundingBox();
  await page.waitForTimeout(200);
  const settled = await caret.boundingBox();
  assert.ok(settled.x > start.x + 5);
  assert.ok(intermediate.x < settled.x - 0.1, 'caret glides rather than instantly jumping');
  assert.equal(await page.locator('.smooth-field-suggestion').textContent(), 'ha beta');
  const baselineGap = await page.evaluate(() => {
    const ghost = document.querySelector('.smooth-field-suggestion');
    const range = document.createRange(); range.selectNodeContents(ghost);
    return Math.abs(range.getBoundingClientRect().top - document.querySelector('[data-slot="smooth-field-caret"]').getBoundingClientRect().top);
  });
  assert.ok(baselineGap < 1.5, 'suggestion shares the native glyph baseline');
  await plain.press('Tab');
  assert.equal(await plain.inputValue(), 'Alpha beta');
  await plain.press('Tab');
  assert.equal(await page.locator('#check-last').evaluate(e => e === document.activeElement), true, 'Tab moves focus once completed');
  await plain.focus();
  await plain.fill('');
  await plain.press('Shift+Tab');
  assert.equal(await page.locator('#check-first').evaluate(e => e === document.activeElement), true);
  await plain.fill('unrelated');
  await plain.press('Tab');
  assert.equal(await plain.inputValue(), 'unrelated');
  await plain.fill('Alpha');
  await plain.evaluate(e => e.setSelectionRange(0, 5));
  await page.waitForFunction(() => document.querySelector('[data-slot="smooth-field-caret"]').style.opacity === '0');
  await plain.press('Tab');
  assert.equal(await plain.inputValue(), 'Alpha', 'Tab never overwrites a selection');
  await plain.focus();
  const composition = await plain.evaluate(e => {
    e.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true }));
    const key = new KeyboardEvent('keydown', { key: 'Tab', bubbles: true, cancelable: true });
    e.dispatchEvent(key);
    e.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true }));
    return key.defaultPrevented;
  });
  assert.equal(composition, false, 'IME keeps its native keys');
  await plain.fill('Al');
  await plain.evaluate(e => e.setAttribute('aria-expanded', 'true'));
  await plain.press('Tab');
  assert.equal(await plain.inputValue(), 'Al', 'an expanded suggestion menu owns its keys');
  await plain.evaluate(e => e.removeAttribute('aria-expanded'));
  await plain.evaluate(e => e.addEventListener('keydown', event => event.preventDefault(), { once: true }));
  await plain.focus();
  await plain.press('Tab');
  assert.equal(await plain.inputValue(), 'Al', 'existing key handlers have precedence');
  for (const id of ['check-secret', 'check-revealed', 'check-readonly', 'check-max']) {
    const field = page.locator(`#${id}`);
    await field.focus();
    await field.press('Tab');
    assert.equal(await field.inputValue(), '', `${id} receives no completion`);
  }
  const secret = page.locator('#check-secret');
  await secret.fill('private');
  await visibleCaret();
  assert.ok(!(await page.locator('.smooth-field-mirror').textContent()).includes('private'), 'password mirror contains only masks');
  await page.locator('#check-number').focus();
  await page.waitForTimeout(40);
  assert.equal(await caret.evaluate(e => e.style.opacity), '0', 'numeric controls stay native');
  await page.locator('#check-email').focus();
  await page.locator('#check-email').press('Tab');
  assert.equal(await page.locator('#check-email').inputValue(), 'me@example.com', 'native email validation is retained');
  assert.equal(await page.locator('#check-email').evaluate(e => e.checkValidity()), true);
  const list = page.locator('#check-list');
  await list.fill('Hel');
  await list.press('Tab');
  assert.equal(await list.inputValue(), 'Hello world');
  const lines = page.locator('#check-lines');
  await lines.fill('First line\nSecond line\nThird line\nFourth line\nFifth line');
  await visibleCaret();
  let box = await lines.boundingBox();
  let painted = await caret.boundingBox();
  assert.ok(painted.y >= box.y && painted.y + painted.height <= box.y + box.height + 1);
  await lines.evaluate(e => { e.scrollTop = 0; });
  await page.waitForFunction(() => document.querySelector('[data-slot="smooth-field-caret"]').style.opacity === '0');
  await lines.evaluate(e => { e.setSelectionRange(2, 2); });
  await visibleCaret();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await plain.fill('long text');
  await visibleCaret();
  await page.waitForTimeout(40);
  const exact = await plain.evaluate(e => {
    const canvas = document.createElement('canvas'); const context = canvas.getContext('2d');
    const style = getComputedStyle(e); context.font = style.font;
    return e.getBoundingClientRect().left + parseFloat(style.borderLeftWidth) + parseFloat(style.paddingLeft) + context.measureText(e.value).width;
  });
  assert.ok(Math.abs((await caret.boundingBox()).x - exact) < 2, 'live reduced motion immediately positions the caret');
  await page.evaluate(() => {
    const dialog = document.createElement('dialog'); dialog.id = 'check-dialog';
    dialog.innerHTML = '<input id="check-dialog-field" placeholder="Hello there">';
    document.body.append(dialog); dialog.showModal();
  });
  const dialogField = page.locator('#check-dialog-field');
  await dialogField.fill('Hel');
  await visibleCaret();
  assert.equal(await page.locator('.smooth-field-layer').evaluate(e => e.matches(':popover-open')), true);
  await page.locator('#check-dialog').screenshot({ path: '/tmp/pr1021-text-dialog.png' });
  await dialogField.press('Tab');
  assert.equal(await dialogField.inputValue(), 'Hello there');
  await page.evaluate(() => document.querySelector('#check-dialog').remove());
  await page.setViewportSize({ width: 390, height: 844 });
  await plain.focus(); await visibleCaret();
  box = await plain.boundingBox(); painted = await caret.boundingBox();
  assert.ok(painted.x >= box.x && painted.x <= box.x + box.width);
  await page.screenshot({ path: '/tmp/pr1021-smooth-fields.png' });
  await page.evaluate(() => document.querySelector('#text-field-check').remove());
  await page.waitForTimeout(40);
  assert.equal(await caret.evaluate(e => e.style.opacity), '0');
  assert.deepEqual(errors, []);
  console.log('PASS shared and raw fields, controlled Flow and composer completion, undo, animated caret, selection, IME, keyboard precedence, secure fields, datalist, multiline scrolling, dialogs, live reduced motion and mobile bounds. No form was saved.');
} finally { await browser.close(); }
