#!/usr/bin/env bash
# Rebuilds src/html-extract.wasm.generated.ts in packages/agent from this
# crate. Reproducible on Linux x86_64: the toolchain is pinned
# (rust-toolchain.toml), absolute paths are remapped and symbols stripped, so
# the bytes do not depend on the machine's paths. They do depend on the host
# OS: a macOS host emits different code for the same target, so the
# checked-in module is the Linux build. CI runs this and fails when the
# checked-in module differs (.github/workflows/rust.yml), attaching its own
# build; on a Mac, take that artifact rather than committing a local build.
set -euo pipefail
cd "$(dirname "$0")"
TARGET_DIR=${CARGO_TARGET_DIR:-target}
export RUSTFLAGS="--remap-path-prefix=$PWD=html-extract --remap-path-prefix=${CARGO_HOME:-$HOME/.cargo}=cargo --remap-path-prefix=${RUSTUP_HOME:-$HOME/.rustup}=rustup"
cargo build --locked --release --target wasm32-unknown-unknown
wasm="$TARGET_DIR/wasm32-unknown-unknown/release/html_extract_wasm.wasm"
{
  echo "// Generated by packages/agent/native/html-extract/build.sh. Do not edit."
  echo "// The Rust HTML extractor (htmlToText, extractPage) compiled to WebAssembly."
  printf 'export const HTML_EXTRACT_WASM_BASE64 =\n  "%s";\n' "$(base64 < "$wasm" | tr -d '\n')"
} > ../../src/html-extract.wasm.generated.ts
echo "wrote src/html-extract.wasm.generated.ts ($(wc -c < "$wasm") bytes of wasm)"
